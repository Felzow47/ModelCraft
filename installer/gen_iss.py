#!/usr/bin/env python3
"""Generate installer/modelcraft.iss (Inno Setup 6) from the extension list in platform.rs.

Run from anywhere:  python3 installer/gen_iss.py
Then build:         iscc installer/modelcraft.iss   (Windows, or Inno Setup under Wine)
"""
import re, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
src = (ROOT / "crates/swcraft/src/platform.rs").read_text(encoding="utf-8")
m = re.search(r"ASSOC_EXTS: &\[&str\] = &\[(.*?)\];", src, re.S)
EXTS = re.findall(r'"([a-z0-9]+)"', m.group(1))
ver = re.search(r'^version = "([^"]+)"', (ROOT / "Cargo.toml").read_text(), re.M).group(1)

# (French label, English label, checked by default). Checked: formats that usually have no
# viewer on the PC. Unchecked: formats another program (slicer, Blender, CAD) often owns.
INFO = {
    "sldprt": ("Pièce SolidWorks", "SolidWorks part", True),
    "sldasm": ("Assemblage SolidWorks", "SolidWorks assembly", True),
    "step": ("STEP", "STEP", True), "stp": ("STEP", "STEP", True),
    "iges": ("IGES", "IGES", True), "igs": ("IGES", "IGES", True),
    "stl": ("Maillage STL", "STL mesh", False),
    "obj": ("Wavefront OBJ", "Wavefront OBJ", False),
    "3ds": ("3D Studio", "3D Studio", False),
    "3dxml": ("3D XML", "3D XML", True),
    "easm": ("eDrawings assemblage", "eDrawings assembly", True),
    "rvt": ("Projet Revit (vignette, infos)", "Revit project (preview, info)", False),
    "rfa": ("Famille Revit (vignette, infos)", "Revit family (preview, info)", False),
    "ifc": ("IFC (BIM)", "IFC (BIM)", True), "ifczip": ("IFC compressé", "Zipped IFC", True),
    "fbx": ("FBX", "FBX", False), "gltf": ("glTF", "glTF", False), "glb": ("glTF binaire", "Binary glTF", False),
    "dae": ("COLLADA", "COLLADA", False), "3mf": ("3MF", "3MF", False), "ply": ("PLY", "PLY", False),
    "off": ("OFF", "OFF", False), "amf": ("AMF", "AMF", False), "wrl": ("VRML", "VRML", False),
    "x3d": ("X3D", "X3D", False), "usdz": ("USDZ", "USDZ", False), "dxf": ("DXF (3D)", "DXF (3D)", False),
}

out = []
w = out.append
w(f"""; Generated by installer/gen_iss.py — edit the generator, not this file.
; ModelCraft {ver} — Windows installer (Inno Setup 6). Per-user by default (no admin rights);
; the extension list comes from ASSOC_EXTS in crates/swcraft/src/platform.rs.

#define AppName "ModelCraft"
#define AppVersion "{ver}"
#define AppExe "modelcraft.exe"
#define ProgId "ModelCraft.Model"

[Setup]
AppId={{{{6F1C2B7E-4D5A-4E3B-9A1C-7D2E8B5F0A41}}
AppName={{#AppName}}
AppVersion={{#AppVersion}}
AppVerName={{#AppName}} {{#AppVersion}}
AppPublisher=ModelCraft (projet indépendant)
DefaultDirName={{autopf}}\\{{#AppName}}
DefaultGroupName={{#AppName}}
DisableProgramGroupPage=yes
PrivilegesRequired=lowest
PrivilegesRequiredOverridesAllowed=dialog
ArchitecturesAllowed=x64compatible
ArchitecturesInstallIn64BitMode=x64compatible
ChangesAssociations=yes
OutputDir=..\\dist
OutputBaseFilename=ModelCraft-Setup-{{#AppVersion}}
SetupIconFile=..\\crates\\swcraft\\assets\\modelcraft.ico
UninstallDisplayIcon={{app}}\\{{#AppExe}}
Compression=lzma2/max
SolidCompression=yes
WizardStyle=modern

[Languages]
Name: "fr"; MessagesFile: "compiler:Languages\\French.isl"
Name: "en"; MessagesFile: "compiler:Default.isl"

[CustomMessages]
fr.Assoc=Ouvrir ces types de fichiers avec ModelCraft :
en.Assoc=Open these file types with ModelCraft:
fr.Desktop=Créer une icône sur le Bureau
en.Desktop=Create a desktop icon
fr.Scanner=Scanner de dossiers (lecture seule)
en.Scanner=Folder scanner (read-only)
fr.Launch=Lancer ModelCraft
en.Launch=Launch ModelCraft
""")
for e in EXTS:
    fr, en, _ = INFO.get(e, (e.upper(), e.upper(), False))
    w(f"fr.ext_{e}=.{e} — {fr}")
    w(f"en.ext_{e}=.{e} — {en}")
w("""
[Tasks]
Name: "desktop"; Description: "{cm:Desktop}"; Flags: unchecked
Name: "assoc"; Description: "{cm:Assoc}"
""")
for e in EXTS:
    on = INFO.get(e, ("", "", False))[2]
    flags = "" if on else "; Flags: unchecked"
    w(f'Name: "assoc\\{e}"; Description: "{{cm:ext_{e}}}"{flags}')
w("""
[Files]
Source: "..\\dist\\modelcraft.exe"; DestDir: "{app}"; Flags: ignoreversion
Source: "..\\dist\\swcraft-scan.exe"; DestDir: "{app}"; Flags: ignoreversion
Source: "..\\README.md"; DestDir: "{app}"; Flags: ignoreversion
Source: "..\\NOTICE.md"; DestDir: "{app}"; Flags: ignoreversion
Source: "..\\licenses\\*"; DestDir: "{app}\\licenses"; Flags: ignoreversion recursesubdirs

[Icons]
Name: "{group}\\{#AppName}"; Filename: "{app}\\{#AppExe}"
Name: "{group}\\{cm:Scanner}"; Filename: "{app}\\swcraft-scan.exe"
Name: "{group}\\{cm:UninstallProgram,{#AppName}}"; Filename: "{uninstallexe}"
Name: "{autodesktop}\\{#AppName}"; Filename: "{app}\\{#AppExe}"; Tasks: desktop

[Registry]
; ProgID (removed on uninstall)
Root: HKA; Subkey: "Software\\Classes\\{#ProgId}"; ValueType: string; ValueName: ""; ValueData: "Modèle 3D ModelCraft"; Flags: uninsdeletekey
Root: HKA; Subkey: "Software\\Classes\\{#ProgId}\\DefaultIcon"; ValueType: string; ValueName: ""; ValueData: "{app}\\{#AppExe},0"
Root: HKA; Subkey: "Software\\Classes\\{#ProgId}\\shell\\open\\command"; ValueType: string; ValueName: ""; ValueData: \"\"\"{app}\\{#AppExe}\"\" \"\"%1\"\"\"
; "Open with" entry
Root: HKA; Subkey: "Software\\Classes\\Applications\\{#AppExe}"; ValueType: string; ValueName: "FriendlyAppName"; ValueData: "{#AppName}"; Flags: uninsdeletekey
Root: HKA; Subkey: "Software\\Classes\\Applications\\{#AppExe}\\shell\\open\\command"; ValueType: string; ValueName: ""; ValueData: \"\"\"{app}\\{#AppExe}\"\" \"\"%1\"\"\"
""".replace('\\"', '"'))
for e in EXTS:
    w(f'; .{e}')
    w(f'Root: HKA; Subkey: "Software\\Classes\\.{e}\\OpenWithProgids"; ValueType: string; ValueName: "{{#ProgId}}"; ValueData: ""; Flags: uninsdeletevalue; Tasks: assoc\\{e}')
    w(f'Root: HKA; Subkey: "Software\\Classes\\.{e}"; ValueType: string; ValueName: ""; ValueData: "{{#ProgId}}"; Flags: uninsdeletevalue; Tasks: assoc\\{e}')
    w(f'Root: HKA; Subkey: "Software\\Classes\\Applications\\{{#AppExe}}\\SupportedTypes"; ValueType: string; ValueName: ".{e}"; ValueData: ""')
w("""
[Run]
Filename: "{app}\\{#AppExe}"; Description: "{cm:Launch}"; Flags: nowait postinstall skipifsilent
""")
(ROOT / "installer/modelcraft.iss").write_text("\n".join(out), encoding="utf-8-sig")
print(f"installer/modelcraft.iss: {len(EXTS)} extensions, version {ver}")
